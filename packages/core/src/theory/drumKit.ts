/** חלקי הערכה שהמנוע מכיר. הסדר הוא מלמטה למעלה בלוח — ראה DRUM_ZONE_THRESHOLDS. */
export const DRUM_PIECES = [
  'kick',
  'tom',
  'snare',
  'clap',
  'hihat-closed',
  'hihat-open',
  'crash',
] as const;

export type DrumPiece = (typeof DRUM_PIECES)[number];

/**
 * הגבול העליון (יחס 0–1 בגובה הלוח) של כל אזור, לפי סדר DRUM_PIECES.
 *
 * ⚠️ האזורים **לא** שווים בכוונה: קיק וסנר הם עמוד השדרה של כל גרוב ומקבלים אזור רחב
 * שקל לפגוע בו, בעוד קראש הוא מבטא נדיר ומקבל את השורה העליונה בלבד. חלוקה שווה הייתה
 * נותנת לקראש בדיוק אותו סיכוי כמו לקיק, וזה לא איך שערכת תופים מתנהגת.
 */
const DRUM_ZONE_THRESHOLDS = [0.2, 0.34, 0.54, 0.68, 0.86, 0.95, 1] as const;

/**
 * ממפה שורה בלוח לכלי בערכה. rowIndex 0 = השורה התחתונה (הנמוכה ביותר).
 */
export function drumPieceForRow(rowIndex: number, rowCount: number): DrumPiece {
  const denominator = Math.max(1, rowCount - 1);
  const position = Math.min(1, Math.max(0, rowIndex / denominator));
  for (let index = 0; index < DRUM_ZONE_THRESHOLDS.length; index += 1) {
    if (position < (DRUM_ZONE_THRESHOLDS[index] ?? 1)) {
      return DRUM_PIECES[index] ?? 'kick';
    }
  }
  return 'crash';
}

/**
 * עוצמה יחסית לכל כלי — קיק וסנר נושאים את הגרוב, היי-האט הוא רקע.
 *
 * ⚠️ **הערכים כוונו לפי מדידת עוצמה נתפסת (LUFS), לא לפי שיא.** כל הדגימות מנורמלות לאותו
 * שיא של −1 dBFS (docs/SAMPLES.md), אבל **שיא זהה אינו עוצמה זהה**: האוזן רגישה הרבה יותר
 * לתדרים גבוהים מאשר ל-50Hz. נמדד על הערכה האלקטרונית: ההיי-האט הפתוח יצא **חזק מהקיק
 * ב-1 dB**, והטום ב-1.8 dB — והמשתמש שמע "מצלתיים ולא תוף", בצדק מלא. הקיק היה רק הרביעי
 * בעוצמה הנתפסת למרות שהוא בגיין 1.0.
 *
 * הערכים למטה מפילים את המתכות ומשאירים את הקיק בראש. מי שמשנה אותם — למדוד LUFS, לא שיא.
 */
export const DRUM_PIECE_GAIN: Record<DrumPiece, number> = {
  kick: 1,
  clap: 1,
  snare: 0.85,
  tom: 0.45,
  crash: 0.35,
  'hihat-open': 0.3,
  'hihat-closed': 0.28,
};
